"""Generate docs/configuration.md from ``Settings`` and ``.env.example``.

Run: python scripts/generate_configuration_docs.py

``.env.example`` is the single source of environment truth: this script turns
it, plus the runtime ``Settings`` model, into the human-readable reference.
``tests/test_configuration_docs.py`` regenerates the file and fails when the
two drift apart, so adding a setting without documenting it (or documenting a
variable that nothing reads) is a test failure rather than a stale doc.
"""

from __future__ import annotations

import sys
from pathlib import Path
from typing import Any, Literal, get_args, get_origin

REPO_ROOT = Path(__file__).resolve().parent.parent
ENV_EXAMPLE = REPO_ROOT / ".env.example"
OUTPUT = REPO_ROOT / "docs" / "configuration.md"

# The Settings model lives in the backend package; make it importable when the
# script is run directly from the repository root.
sys.path.insert(0, str(REPO_ROOT / "backend"))

from app.core.config import Settings  # noqa: E402  (needs the sys.path entry above)

# Environment variables read directly by modules rather than through the
# Settings model. The generator refuses to render a variable it cannot
# attribute to one of the two sources, so a new variable must be classified
# deliberately and this mapping kept in sync with the code that reads it.
DIRECT_VARIABLE_DEFAULTS: dict[str, str] = {
    "AEGIS_REPORT_DIR": "`/tmp/aegis/reports`",
}


def _parse_env_example(text: str) -> list[tuple[str, str, str]]:
    """Return ``(key, value, description)`` for every variable in the file.

    A variable's description is the comment block immediately above it. A
    blank line or a lone ``#`` resets the block, so section headers can stay
    in the file for human readers without leaking into the reference table.
    """
    entries: list[tuple[str, str, str]] = []
    comments: list[str] = []
    for raw_line in text.splitlines():
        line = raw_line.strip()
        if not line:
            comments = []
        elif line.startswith("#"):
            comment = line.lstrip("#").strip()
            if comment:
                comments.append(comment)
            else:
                comments = []
        elif "=" in line:
            key, _, value = line.partition("=")
            entries.append((key.strip(), value.strip(), " ".join(comments)))
            comments = []
    return entries


def _type_label(annotation: Any) -> str:
    if get_origin(annotation) is Literal:
        choices = ", ".join(f"`{choice}`" for choice in get_args(annotation))
        return f"one of {choices}"
    return f"`{getattr(annotation, '__name__', str(annotation))}`"


def _default_label(default: Any) -> str:
    if isinstance(default, bool):
        return "`true`" if default else "`false`"
    if default == "":
        return "(empty)"
    return f"`{default}`"


def render() -> str:
    """Render the full configuration reference as Markdown."""

    env_text = ENV_EXAMPLE.read_text(encoding="utf-8")
    entries = _parse_env_example(env_text)
    fields = Settings.model_fields
    documented = {key for key, _, _ in entries}

    rows: list[str] = []
    for key, _value, description in entries:
        field = fields.get(key.lower())
        if field is not None:
            type_label = _type_label(field.annotation)
            default_label = _default_label(field.default)
        elif key in DIRECT_VARIABLE_DEFAULTS:
            type_label = "(read directly)"
            default_label = DIRECT_VARIABLE_DEFAULTS[key]
        else:
            raise SystemExit(
                f".env.example defines {key}, which is neither a Settings field "
                "nor listed in DIRECT_VARIABLE_DEFAULTS"
            )
        # Markdown tables break on raw pipes; the env file may still use them
        # (APP_ENV lists its choices that way).
        table_description = description.replace("|", "\\|") if description else "-"
        rows.append(f"| `{key}` | {type_label} | {default_label} | {table_description} |")

    missing = sorted(name.upper() for name in fields if name.upper() not in documented)
    if missing:
        raise SystemExit("Settings fields missing from .env.example: " + ", ".join(missing))

    lines = [
        "# Configuration",
        "",
        "<!-- Generated by scripts/generate_configuration_docs.py.",
        "     Do not edit by hand: change backend/app/core/config.py or",
        "     .env.example and rerun the script; a test fails when this file",
        "     drifts from those sources. -->",
        "",
        "Aegis Vuldris is configured entirely through environment variables. A `.env`",
        "file in the working directory is read when present, but the environment",
        "takes priority; deployed systems should inject variables from a secrets",
        "manager and never ship a `.env`. See",
        "[secrets-management.md](secrets-management.md) for handling rules and",
        "[deployment.md](deployment.md) for production values.",
        "",
        "Regenerate this reference with:",
        "",
        "```bash",
        "python scripts/generate_configuration_docs.py",
        "```",
        "",
        "## Variables",
        "",
        "| Variable | Type | Default | Description |",
        "| --- | --- | --- | --- |",
        *rows,
        "",
        "## Example `.env`",
        "",
        "The annotated template. Copy it and fill in the required values; the",
        "template itself is safe to commit, a real `.env` never is.",
        "",
        "```dotenv",
        env_text.rstrip("\n"),
        "```",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    rendered = render()
    if OUTPUT.is_file() and OUTPUT.read_text(encoding="utf-8") == rendered:
        print(f"{OUTPUT.relative_to(REPO_ROOT)} is up to date")
        return 0
    with open(OUTPUT, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(rendered)
    print(f"Wrote {OUTPUT.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
